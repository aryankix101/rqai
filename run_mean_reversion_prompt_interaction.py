"""Run and analyze the predeclared development-only prompt interaction suite.

The suite is generated by ``mean_reversion_research_diagnostics.py prompt-suite``.
This supervisor runs B, C, and D sequentially. B first collects one fresh A
(minimal-change) control; C and D then reuse that exact frozen A artifact. It
is resumable from immutable caches and refuses any command whose date range
reaches the blind period.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd

import mean_reversion_research_diagnostics as diagnostics


PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_SUITE = (
    PROJECT_ROOT
    / "backtest_results/research_thesis_package_20260808/prompt_interaction/suite_manifest.json"
)
ARMS = ("B", "C", "D")


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def write_json(path: Path, payload: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        json.dumps(diagnostics._json_safe(payload), indent=2, sort_keys=True),
        encoding="utf-8",
    )
    temporary.replace(path)


def read_suite(path: Path) -> dict[str, Any]:
    suite = diagnostics._read_json(path)
    if not suite.get("development_only") or suite.get("blind_period_touched"):
        raise diagnostics.ResearchDiagnosticError(
            "Prompt interaction suite is not marked development-only"
        )
    if set(suite.get("commands", {})) != set(ARMS):
        raise diagnostics.ResearchDiagnosticError("Suite must contain exactly B/C/D commands")
    manifest = diagnostics._read_json(Path(str(suite["manifest"])))
    diagnostics._assert_development_dates(
        manifest.get("dates", []), source=str(suite["manifest"])
    )
    for arm in ARMS:
        command = [str(value) for value in suite["commands"][arm]]
        for flag, expected in (("--start", "2009-01-01"), ("--end", "2014-01-01")):
            if flag not in command or command[command.index(flag) + 1] != expected:
                raise diagnostics.ResearchDiagnosticError(
                    f"Arm {arm} violates the frozen development range"
                )
        if "--validation-freeze" in command:
            raise diagnostics.ResearchDiagnosticError(
                f"Arm {arm} unexpectedly requests validation"
            )
        if ("--paired-control" in command) != (arm == "B"):
            raise diagnostics.ResearchDiagnosticError(
                "Exactly arm B must collect the single shared A control"
            )
    return suite


def arm_paths(suite_path: Path, arm: str) -> dict[str, Path]:
    root = suite_path.parent / f"arm_{arm.lower()}"
    variant = root / "run/pool60_pos30/anchor_3"
    shared_variant = suite_path.parent / "arm_b/run/pool60_pos30/anchor_3"
    return {
        "root": root,
        "run": root / "run",
        "log": root / "supervisor_runner.log",
        "scorecard": root / "run/comparison_scorecard.csv",
        "config": root / "run/run_config.json",
        "treatment": variant / "llm_pool_experimental",
        "control": shared_variant / "llm_pool_v2_minimal_change_fresh_control",
        "trail5": variant / "baseline_pool",
        "prompt_spec": suite_path.parent / "prompt_specs" / f"arm_{arm.lower()}.json",
        "pair_result": root / "paired_result.json",
        "diagnostics": root / "diagnostics",
    }


def arm_complete(paths: dict[str, Path]) -> bool:
    required = (
        paths["scorecard"],
        paths["config"],
        paths["treatment"] / "weekly_returns.csv",
        paths["treatment"] / "signal_checks.csv",
        paths["control"] / "weekly_returns.csv",
        paths["control"] / "signal_checks.csv",
        paths["trail5"] / "weekly_returns.csv",
    )
    if not all(path.is_file() for path in required):
        return False
    for run_dir in (paths["treatment"], paths["control"], paths["trail5"]):
        dates = pd.read_csv(run_dir / "weekly_returns.csv", usecols=["date"])["date"]
        diagnostics._assert_development_dates(dates, source=str(run_dir))
        if len(pd.Index(pd.to_datetime(dates).dt.normalize()).unique()) != 251:
            return False
    return True


def run_suite(suite_path: Path, *, arms: Sequence[str] = ARMS) -> dict[str, Any]:
    suite_path = Path(suite_path).resolve()
    suite = read_suite(suite_path)
    state_path = suite_path.parent / "execution_state.json"
    state = (
        diagnostics._read_json(state_path)
        if state_path.is_file()
        else {
            "schema_version": 1,
            "status": "initialized",
            "started_at": utc_now(),
            "blind_period_touched": False,
            "arms": {},
        }
    )
    state.update({"status": "running", "pid": os.getpid(), "updated_at": utc_now()})
    write_json(state_path, state)
    for arm in arms:
        arm = str(arm).upper()
        if arm not in ARMS:
            raise diagnostics.ResearchDiagnosticError(f"Unknown interaction arm {arm!r}")
        paths = arm_paths(suite_path, arm)
        if arm != "B" and not arm_complete(arm_paths(suite_path, "B")):
            raise diagnostics.ResearchDiagnosticError(
                "The single shared A control and arm B must complete before C or D"
            )
        if arm_complete(paths):
            state["arms"][arm] = {"status": "completed", "resumed": True, "updated_at": utc_now()}
            write_json(state_path, state)
            continue
        paths["root"].mkdir(parents=True, exist_ok=True)
        command = [str(value) for value in suite["commands"][arm]]
        state["arms"][arm] = {"status": "running", "updated_at": utc_now()}
        state["current_arm"] = arm
        write_json(state_path, state)
        with paths["log"].open("a", encoding="utf-8") as log_handle:
            log_handle.write(f"\n[{utc_now()}] starting arm {arm}\n")
            log_handle.flush()
            completed = subprocess.run(
                command,
                cwd=PROJECT_ROOT,
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                check=False,
            )
        if completed.returncode != 0 or not arm_complete(paths):
            state.update({"status": "failed", "current_arm": None, "updated_at": utc_now()})
            state["arms"][arm] = {
                "status": "failed",
                "returncode": completed.returncode,
                "log": str(paths["log"]),
                "updated_at": utc_now(),
            }
            write_json(state_path, state)
            raise diagnostics.ResearchDiagnosticError(
                f"Prompt arm {arm} failed; inspect {paths['log']}"
            )
        state["arms"][arm] = {
            "status": "completed",
            "returncode": completed.returncode,
            "updated_at": utc_now(),
        }
        write_json(state_path, state)
    state.update(
        {
            "status": "completed",
            "current_arm": None,
            "completed_at": utc_now(),
            "updated_at": utc_now(),
            "blind_period_touched": False,
        }
    )
    write_json(state_path, state)
    return state


def paired_artifact_for_arm(suite_path: Path, arm: str) -> diagnostics.PairedArtifacts:
    paths = arm_paths(suite_path, arm)
    if not arm_complete(paths):
        raise diagnostics.ResearchDiagnosticError(f"Arm {arm} is incomplete")
    control_artifact = {
        "weekly_returns_sha256": diagnostics._sha256_file(
            paths["control"] / "weekly_returns.csv"
        ),
        "signal_checks_sha256": diagnostics._sha256_file(
            paths["control"] / "signal_checks.csv"
        ),
    }
    write_json(
        paths["pair_result"],
        {
            "candidate_id": arm,
            "stage": "full",
            "artifacts": {
                "treatment": str(paths["treatment"]),
                "control": str(paths["control"]),
                "trail5": str(paths["trail5"]),
                "control_artifact": control_artifact,
            },
        },
    )
    return diagnostics.PairedArtifacts(
        label=f"Fresh prompt interaction arm {arm}",
        candidate_id=arm,
        campaign_dir=suite_path.parent,
        stage_dir=paths["root"],
        treatment_dir=paths["treatment"],
        control_dir=paths["control"],
        trail5_dir=paths["trail5"],
        result_path=paths["pair_result"],
        prompt_spec_path=paths["prompt_spec"],
    )


def analyze_suite(suite_path: Path, *, n_boot: int = 5_000) -> dict[str, Any]:
    suite_path = Path(suite_path).resolve()
    read_suite(suite_path)
    summaries: dict[str, dict[str, Any]] = {}
    delta_by_arm: dict[str, pd.DataFrame] = {}
    shared_control = diagnostics.load_weekly(
        arm_paths(suite_path, "B")["control"]
    )[["date", "capital_c2c"]]
    control_rows = [
        {
            "control_replicate": "shared_A",
            **diagnostics.return_metrics(shared_control["capital_c2c"]),
        }
    ]
    for arm in ARMS:
        artifacts = paired_artifact_for_arm(suite_path, arm)
        paths = arm_paths(suite_path, arm)
        summary = diagnostics.full_stage_diagnostics(
            artifacts, paths["diagnostics"], n_boot=n_boot
        )
        factor_summary = diagnostics.conditional_factor_strength_study(
            artifacts, paths["factor_strength"], n_boot=n_boot
        )
        summary["conditional_factor_strength"] = factor_summary
        summaries[arm] = summary
        candidate = diagnostics.load_weekly(paths["treatment"])[["date", "capital_c2c"]]
        control = diagnostics.load_weekly(paths["control"])[["date", "capital_c2c"]]
        paired = candidate.merge(
            control,
            on="date",
            suffixes=("_treatment", "_control"),
            validate="one_to_one",
        )
        paired[f"delta_{arm}"] = paired["capital_c2c_treatment"] - paired["capital_c2c_control"]
        delta_by_arm[arm] = paired[["date", f"delta_{arm}"]]

    effects = delta_by_arm["B"]
    for arm in ("C", "D"):
        effects = effects.merge(delta_by_arm[arm], on="date", validate="one_to_one")
    effects["interaction_D_minus_B_minus_C"] = (
        effects["delta_D"] - effects["delta_B"] - effects["delta_C"]
    )
    effect_rows: list[dict[str, Any]] = []
    for label, column in (
        ("B minus fresh A", "delta_B"),
        ("C minus fresh A", "delta_C"),
        ("D minus fresh A", "delta_D"),
        ("D interaction beyond B plus C", "interaction_D_minus_B_minus_C"),
    ):
        bootstrap = diagnostics.moving_block_bootstrap(
            effects[column], n_boot=n_boot, seed=3100 + len(effect_rows)
        )
        effect_rows.append({"effect": label, **bootstrap})
    effect_table = pd.DataFrame(effect_rows)
    control_table = pd.DataFrame(control_rows)
    analysis_dir = suite_path.parent / "analysis"
    analysis_dir.mkdir(parents=True, exist_ok=True)
    effects.to_csv(analysis_dir / "paired_interaction_effects_by_date.csv", index=False)
    effect_table.to_csv(analysis_dir / "interaction_effects.csv", index=False)
    control_table.to_csv(analysis_dir / "fresh_A_control_replicates.csv", index=False)
    ranking = sorted(
        (
            {
                "arm": arm,
                "paired_lift_pct": summary["annualized_paired_lift_pct"],
                "ci_low_pct": summary["bootstrap"]["ci_95_low_pct"],
                "probability_positive": summary["bootstrap"]["probability_lift_gt_zero"],
                "block_stability_pct": summary["chronological_block_stability_pct"],
                "trimmed_5pct_lift_pct": summary["trimmed_5pct_annualized_lift_pct"],
                "long_lift_pct": summary["long_annualized_lift_pct"],
                "short_lift_pct": summary["short_annualized_lift_pct"],
                "weak_state_lift_pct": summary["conditional_factor_strength"]
                ["weakest_quintile"]["paired_llm_minus_trail5_lift_pct"],
                "weak_state_ci_low_pct": summary["conditional_factor_strength"]
                ["weakest_quintile"]["bootstrap_ci_low_pct"],
            }
            for arm, summary in summaries.items()
        ),
        key=lambda row: (
            not (row["trimmed_5pct_lift_pct"] > 0.0),
            -row["block_stability_pct"],
            not (row["long_lift_pct"] >= 0.0 and row["short_lift_pct"] >= 0.0),
            not (row["weak_state_lift_pct"] > 0.0),
            -min(row["long_lift_pct"], row["short_lift_pct"]),
            -row["ci_low_pct"],
            -row["paired_lift_pct"],
            row["arm"],
        ),
    )
    pd.DataFrame(ranking).to_csv(analysis_dir / "arm_robustness_ranking.csv", index=False)
    summary = {
        "schema_version": 1,
        "status": "completed",
        "development_only": True,
        "blind_period_touched": False,
        "arms": summaries,
        "interaction_effects": effect_rows,
        "fresh_A_controls": control_rows,
        "robustness_ranking": ranking,
        "best_arm": ranking[0]["arm"],
        "additivity_assumed": False,
    }
    write_json(analysis_dir / "summary.json", summary)
    return summary


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("run", "analyze", "run-and-analyze"))
    parser.add_argument("--suite", type=Path, default=DEFAULT_SUITE)
    parser.add_argument("--arms", default="B,C,D")
    parser.add_argument("--n-boot", type=int, default=5_000)
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    selected_arms = tuple(value.strip().upper() for value in args.arms.split(",") if value.strip())
    result: dict[str, Any] = {}
    if args.command in {"run", "run-and-analyze"}:
        result["execution"] = run_suite(args.suite, arms=selected_arms)
    if args.command in {"analyze", "run-and-analyze"}:
        if set(selected_arms) != set(ARMS):
            raise diagnostics.ResearchDiagnosticError("Analysis requires completed B/C/D arms")
        result["analysis"] = analyze_suite(args.suite, n_boot=args.n_boot)
    print(json.dumps(diagnostics._json_safe(result), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
